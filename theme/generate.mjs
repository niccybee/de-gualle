/** Pure, dependency-free theme generation. Used by the docs and CSS build. */
export function normalizeHex(value) {
  if (
    typeof value !== "string" ||
    !/^#(?:[\da-f]{3}|[\da-f]{6})$/i.test(value.trim())
  ) {
    throw new Error("Enter a HEX colour such as #d43f32 or #f64.");
  }
  const hex = value.trim().toLowerCase();
  return hex.length === 4
    ? "#" + [...hex.slice(1)].map((c) => c + c).join("")
    : hex;
}

const rgb = (hex) =>
  normalizeHex(hex)
    .slice(1)
    .match(/../g)
    .map((c) => parseInt(c, 16));
const hex = (channels) =>
  "#" +
  channels
    .map((c) =>
      Math.round(Math.max(0, Math.min(255, c)))
        .toString(16)
        .padStart(2, "0"),
    )
    .join("");
export function mix(a, b, amount) {
  const other = rgb(b);
  return hex(rgb(a).map((c, i) => c + (other[i] - c) * amount));
}
export function luminance(colour) {
  const channels = rgb(colour).map((c) => {
    const s = c / 255;
    return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  });
  return channels[0] * 0.2126 + channels[1] * 0.7152 + channels[2] * 0.0722;
}
export function contrast(a, b) {
  const x = luminance(a),
    y = luminance(b);
  return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05);
}
function readableAccent(seed, surface) {
  const endpoint = luminance(surface) > 0.179 ? "#000000" : "#ffffff";
  for (let step = 0; step <= 100; step++) {
    const candidate = mix(seed, endpoint, step / 100);
    if (contrast(candidate, surface) >= 4.5) return candidate;
  }
  return endpoint;
}
export function generateTheme(input) {
  const seed = normalizeHex(input);
  const scale = {};
  for (const [level, ratio] of [
    [50, 0.96],
    [100, 0.9],
    [200, 0.75],
    [300, 0.55],
    [400, 0.28],
  ]) {
    scale[`--dg-primary-${level}`] = mix(seed, "#ffffff", ratio);
  }
  scale["--dg-primary-500"] = seed;
  for (const [level, ratio] of [
    [600, 0.14],
    [700, 0.3],
    [800, 0.48],
    [900, 0.66],
    [950, 0.82],
  ]) {
    scale[`--dg-primary-${level}`] = mix(seed, "#000000", ratio);
  }
  function mode(dark) {
    const surface = dark ? "#191c1b" : "#faf9f6";
    const panel = dark ? "#222624" : "#ffffff";
    let primary = readableAccent(seed, surface);
    // Links also appear on panels. Preserve sufficient contrast on both surfaces.
    if (contrast(primary, panel) < 4.5)
      primary = readableAccent(primary, panel);
    const onPrimary =
      contrast(primary, "#ffffff") >= contrast(primary, "#000000")
        ? "#ffffff"
        : "#000000";
    const hover = mix(primary, dark ? "#ffffff" : "#000000", 0.12);
    return {
      ...scale,
      "--dg-brand": seed,
      "--dg-background": surface,
      "--dg-surface": panel,
      "--dg-surface-muted": dark ? "#2c322e" : "#efeee9",
      "--dg-text": dark ? "#f2f3ee" : "#242923",
      "--dg-muted": dark ? "#b1b9b1" : "#62685e",
      "--dg-border": dark ? "#737e74" : "#81877b",
      "--dg-divider": dark ? "#3b443d" : "#dedfd6",
      "--dg-primary": primary,
      "--dg-on-primary": onPrimary,
      "--dg-primary-hover": hover,
      "--dg-on-primary-hover":
        contrast(hover, "#fff") >= contrast(hover, "#000")
          ? "#ffffff"
          : "#000000",
      "--dg-tint": mix(seed, panel, dark ? 0.86 : 0.94),
      "--dg-error": dark ? "#ffb4ab" : "#a72620",
      "--dg-success": dark ? "#9bd8af" : "#24613b",
      "--dg-warning": dark ? "#efce8c" : "#795100",
      "--dg-focus": primary,
    };
  }
  return { seed, light: mode(false), dark: mode(true) };
}
export const declarations = (tokens) =>
  Object.entries(tokens)
    .map(([key, value]) => `  ${key}: ${value};`)
    .join("\n");
export function themeCSS(input, selector = "[data-de-gualle]") {
  // Selector is deliberately restricted: never interpolate arbitrary CSS from UI input.
  if (!["[data-de-gualle]", "body", ":root"].includes(selector))
    throw new Error("Unsupported theme boundary.");
  const { light, dark } = generateTheme(input);
  return `/* Generated by de-gualle. Load after the library. */\n${selector} {\n${declarations(light)}\n}\n@media (prefers-color-scheme: dark) {\n  ${selector}:not([data-theme="light"]) {\n${declarations(dark)}\n  }\n}\n${selector}[data-theme="dark"] {\n${declarations(dark)}\n}\n${selector}[data-theme="light"] {\n${declarations(light)}\n}\n`;
}
